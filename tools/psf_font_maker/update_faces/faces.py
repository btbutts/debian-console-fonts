"""Build the text of mk/faces.mk from console-setup's Makefile."""

from __future__ import annotations

import json
import re
from typing import TYPE_CHECKING

from psf_font_maker.common.errors import ToolError

if TYPE_CHECKING:
    from pathlib import Path

START = re.compile(r"^[A-Za-z0-9]+-BDFS\s*:=")
END = re.compile(r"^include \$\(fntdir\)/soft\.Makefile")
GOOD = re.compile(
    r"GOOD_FONT_NAMES\s*:=\s*\$\(filter(.*?),\s*\\\n\s*\$\(I18N_FONT_NAMES\)\)",
    re.DOTALL,
)


def data_block(text: str) -> str:
    """Return the declarative part of console-setup's Makefile, with our two renames."""
    lines = text.splitlines()
    first = next(i for i, line in enumerate(lines) if START.match(line))
    last = next(i for i, line in enumerate(lines) if END.match(line))
    body = "\n".join(lines[first:last]).rstrip() + "\n"
    body = re.sub(r"^FACES(\s*:=)", r"ALL_FACES\1", body, flags=re.MULTILINE)
    return re.sub(r"^CODESETS(\s*:=)", r"ALL_CODESETS\1", body, flags=re.MULTILINE)


def good_faces(text: str) -> list[str]:
    """Return the face names of console-setup's GOOD_FONT_NAMES filter."""
    match = GOOD.search(text)
    if not match:
        message = "could not find GOOD_FONT_NAMES in the console-setup Makefile"
        raise ToolError(message)
    return re.findall(r"%-(\S+)", match.group(1).replace("\\\n", " "))


def console_setup_version(lock: Path) -> str:
    """Return the console-setup version recorded in the lock file, if there is one."""
    if not lock.is_file():
        return "unknown"
    data = json.loads(lock.read_text(encoding="utf-8"))
    return data["sources"]["console-setup"]["version"]


def render(makefile: Path, lock: Path) -> str:
    """Return the full text of mk/faces.mk."""
    text = makefile.read_text(encoding="utf-8")
    version = console_setup_version(lock)
    header = (
        f"# GENERATED by update-faces from console-setup {version} Fonts/Makefile.\n"
        "# Do not edit; change sources.json and run `make update-faces` instead.\n"
        "# console-setup is GPL-2.0-or-later (Copyright Anton Zinoviev and others).\n"
        "# FACES and CODESETS are renamed ALL_FACES and ALL_CODESETS here.\n\n"
    )
    faces = " ".join(good_faces(text))
    footer = (
        "\n# Faces console-setup ships by default (its GOOD_FONT_NAMES filter).\n"
        f"GOOD_FACES := {faces}\n"
    )
    return header + data_block(text) + footer
