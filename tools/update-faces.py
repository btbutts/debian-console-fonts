#!/usr/bin/env python3
"""Regenerate mk/faces.mk from console-setup's Fonts/Makefile.

mk/faces.mk holds the data our Makefile needs: which BDF files make up each
font face, the legacy VGA tables, the face and code set lists, and the list of
faces console-setup considers "good". It is copied verbatim from
sources/console-setup/Fonts/Makefile (only FACES and CODESETS are renamed to
ALL_FACES and ALL_CODESETS, because those names are our command-line options).

    tools/update-faces.py            rewrite mk/faces.mk
    tools/update-faces.py --check    exit 1 if mk/faces.mk is out of date
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEBIAN_MAKEFILE = ROOT / "sources" / "console-setup" / "Fonts" / "Makefile"
LOCK = ROOT / "sources" / "sources.lock.json"
TARGET = ROOT / "mk" / "faces.mk"

START = re.compile(r"^[A-Za-z0-9]+-BDFS\s*:=")
END = re.compile(r"^include \$\(fntdir\)/soft\.Makefile")
GOOD = re.compile(r"GOOD_FONT_NAMES\s*:=\s*\$\(filter(.*?),\s*\\\n\s*\$\(I18N_FONT_NAMES\)\)", re.S)


def render() -> str:
    text = DEBIAN_MAKEFILE.read_text(encoding="utf-8")
    lines = text.splitlines()
    first = next(i for i, line in enumerate(lines) if START.match(line))
    last = next(i for i, line in enumerate(lines) if END.match(line))
    body = "\n".join(lines[first:last]).rstrip() + "\n"
    body = re.sub(r"^FACES(\s*:=)", r"ALL_FACES\1", body, flags=re.M)
    body = re.sub(r"^CODESETS(\s*:=)", r"ALL_CODESETS\1", body, flags=re.M)

    match = GOOD.search(text)
    if not match:
        raise SystemExit("could not find GOOD_FONT_NAMES in the console-setup Makefile")
    good = re.findall(r"%-(\S+)", match.group(1).replace("\\\n", " "))

    version = "unknown"
    if LOCK.is_file():
        version = json.loads(LOCK.read_text(encoding="utf-8"))["sources"]["console-setup"]["version"]
    header = (
        "# GENERATED by tools/update-faces.py from console-setup {version} Fonts/Makefile.\n"
        "# Do not edit; change sources.json and run `make update-faces` instead.\n"
        "# console-setup is GPL-2.0-or-later (Copyright Anton Zinoviev and others).\n"
        "# FACES and CODESETS are renamed ALL_FACES and ALL_CODESETS here.\n\n"
    ).format(version=version)
    footer = (
        "\n# Faces console-setup ships by default (its GOOD_FONT_NAMES filter).\n"
        "GOOD_FACES := {faces}\n"
    ).format(faces=" ".join(good))
    return header + body + footer


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if mk/faces.mk is stale")
    args = parser.parse_args()
    if not DEBIAN_MAKEFILE.is_file():
        print(f"error: {DEBIAN_MAKEFILE} not found; run the downloader first", file=sys.stderr)
        return 1
    new = render()
    if args.check:
        if not TARGET.is_file() or TARGET.read_text(encoding="utf-8") != new:
            print("mk/faces.mk is out of date: run `make update-faces`", file=sys.stderr)
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(new, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({new.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
